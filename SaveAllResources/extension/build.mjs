// Builds the "Save All Resources (Automation Build)" unpacked extension into extension/dist.
//
//  - Starts from the unmodified upstream 2.0.6 build (vendor/save-all-resources-2.0.6/dist):
//    the DevTools panel, popup and legacy versions keep working exactly as before.
//  - Replaces the empty upstream background.js with the automation service worker, bundled from
//    extension/src plus the upstream collection/packaging modules recovered from the 2.0.6
//    source map (vendor/save-all-resources-2.0.6/recovered-src).
//  - Adds permissions (debugger, storage, alarms, unlimitedStorage) and externally_connectable.
//  - Uses its own manifest key so it never collides with the Chrome Web Store extension id.
//
// Configuration: extension/extension.config.json (or env SAR_ALLOWED_APP_ORIGINS /
// SAR_ALLOWED_UPLOAD_ORIGINS as comma separated lists).

import { build } from 'esbuild';
import { createHash, generateKeyPairSync } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const upstream = join(root, 'vendor/save-all-resources-2.0.6');
const outDir = process.env.SAR_EXTENSION_OUT ? resolve(process.env.SAR_EXTENSION_OUT) : join(here, 'dist');

function loadConfig() {
  const file = process.env.SAR_EXTENSION_CONFIG || join(here, 'extension.config.json');
  const base = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : JSON.parse(readFileSync(join(here, 'extension.config.example.json'), 'utf8'));
  const list = (v) => v.split(',').map((s) => s.trim()).filter(Boolean);
  const cfg = {
    allowedAppOrigins: process.env.SAR_ALLOWED_APP_ORIGINS ? list(process.env.SAR_ALLOWED_APP_ORIGINS) : base.allowedAppOrigins,
    allowedUploadOrigins: process.env.SAR_ALLOWED_UPLOAD_ORIGINS ? list(process.env.SAR_ALLOWED_UPLOAD_ORIGINS) : base.allowedUploadOrigins,
  };
  for (const key of ['allowedAppOrigins', 'allowedUploadOrigins']) {
    if (!Array.isArray(cfg[key]) || !cfg[key].length) throw new Error(`${key} must list at least one origin`);
    cfg[key] = cfg[key].map((o) => {
      const u = new URL(o);
      if (u.origin !== o.replace(/\/$/, '')) throw new Error(`${key}: "${o}" must be a bare origin (scheme://host[:port])`);
      if (u.protocol !== 'https:' && !['localhost', '127.0.0.1', '[::1]'].includes(u.hostname)) {
        throw new Error(`${key}: "${o}" must use https (http is only accepted for localhost)`);
      }
      return u.origin;
    });
  }
  return cfg;
}

/** The manifest "key" (public key) pins the extension id. The private key is not needed for unpacked loading. */
function loadOrCreateKey() {
  const keyFile = join(here, 'manifest-key.txt');
  if (!existsSync(keyFile)) {
    const { publicKey } = generateKeyPairSync('rsa', { modulusLength: 2048 });
    writeFileSync(keyFile, publicKey.export({ type: 'spki', format: 'der' }).toString('base64') + '\n');
  }
  const key = readFileSync(keyFile, 'utf8').trim();
  const hash = createHash('sha256').update(Buffer.from(key, 'base64')).digest('hex').slice(0, 32);
  const id = [...hash].map((c) => String.fromCharCode(97 + parseInt(c, 16))).join('');
  return { key, id };
}

/** externally_connectable match patterns: scheme://host/* (ports are enforced at runtime). */
function matchPatterns(origins) {
  return [...new Set(origins.map((o) => `${new URL(o).protocol}//${new URL(o).hostname}/*`))];
}

export async function buildExtension() {
  const cfg = loadConfig();
  const { key, id } = loadOrCreateKey();
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  cpSync(join(upstream, 'dist'), outDir, { recursive: true });

  const upstreamManifest = JSON.parse(readFileSync(join(upstream, 'dist/manifest.json'), 'utf8'));
  const manifest = {
    ...upstreamManifest,
    name: 'Save All Resources (Automation Build)',
    description: 'Save All Resources 2.0.6 with a controlled messaging interface for automated, multi-page website capture.',
    version: '2.0.6.1',
    version_name: '2.0.6-automation.1',
    key,
    background: { service_worker: 'background.js', type: 'module' },
    permissions: [...new Set([...upstreamManifest.permissions, 'debugger', 'storage', 'alarms', 'unlimitedStorage'])],
    externally_connectable: { matches: matchPatterns(cfg.allowedAppOrigins), ids: [] },
  };
  delete manifest.update_url; // must not be replaced by the Web Store build on update
  writeFileSync(join(outDir, 'manifest.json'), JSON.stringify(manifest, null, 2));

  const genDir = join(here, 'src/background');
  writeFileSync(
    join(genDir, 'build-config.js'),
    `// Generated by extension/build.mjs — do not edit.\nexport const BUILD_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`
  );

  await build({
    entryPoints: [join(here, 'src/background/index.js')],
    outfile: join(outDir, 'background.js'),
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'chrome116',
    alias: { devtoolApp: join(upstream, 'recovered-src/src/devtoolApp') },
    define: { 'process.env.NODE_ENV': '"production"' },
    nodePaths: [join(root, 'node_modules')],
    legalComments: 'none',
    logLevel: 'warning',
    banner: { js: '// Save All Resources (Automation Build) — GPL-3.0-or-later. Upstream: https://github.com/up209d/ResourcesSaverExt' },
  });

  writeFileSync(join(outDir, 'AUTOMATION-BUILD.txt'), `extension id: ${id}\nallowed app origins: ${cfg.allowedAppOrigins.join(', ')}\nallowed upload origins: ${cfg.allowedUploadOrigins.join(', ')}\nbuilt: ${new Date().toISOString()}\n`);
  writeFileSync(join(outDir, 'extension-id.txt'), id);
  return { outDir, id, config: cfg };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { outDir: dir, id, config } = await buildExtension();
  console.log(`Built ${dir}\nExtension id: ${id}\nApp origins: ${config.allowedAppOrigins.join(', ')}`);
}
