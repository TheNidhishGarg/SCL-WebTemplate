// Lowercase, ASCII, hyphenated; matches the Slug schema in src/domain/ids.ts.
export function slugify(text: string, maxLength = 56): string {
  return text
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, maxLength)
    .replace(/-+$/, "");
}
